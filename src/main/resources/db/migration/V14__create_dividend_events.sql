create table dividend_events (
     id bigint generated by default as identity,
     ticker varchar(255) not null,
     payment_date date not null,
     ex_dividend_date date,
     amount_per_share numeric(19, 6),
     received_eur numeric(19, 4),
     constraint dividend_events_pkey primary key (id),
     constraint dividend_events_payment_key unique (ticker, payment_date)
);

create table dividend_checks (
     ticker varchar(255),
     checked_at timestamp(6) with time zone not null,
     constraint dividend_checks_pkey primary key (ticker)
);
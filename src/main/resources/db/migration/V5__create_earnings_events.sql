create table earnings_events (
    id BIGINT generated by default as identity,
    ticker varchar(255) not null,
    fiscal_year integer not null ,
    fiscal_quarter integer not null,
    report_date date not null,
    report_hour varchar(10),
    eps_estimate numeric(19, 4),
    eps_actual numeric(19, 4),
    revenue_estimate numeric(19, 4),
    revenue_actual numeric(19, 4),
    eps_yoy numeric(19, 4),
    revenue_yoy numeric(19, 4),
    constraint earnings_events_pkey primary key (id),
    constraint earnings_events_period_key unique (ticker, fiscal_year, fiscal_quarter),
    constraint earnings_events_quarter_check check (fiscal_quarter between 1 and 4)
);